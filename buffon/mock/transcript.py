"""Scripted transcripts: the model's replies as data, so every arm gets the same answers byte for byte.

A transcript is a JSON file (or dict). Request number i of a session gets step i; the last step repeats. The same transcript always produces the same
replies for the same request sequence: ids are derived from the request index and nothing is random or timed.

    {"name": "stream-prose-6000",
     "steps": [ {"text": "...", "chunk_chars": 24, "event_delay_ms": 6},
                {"shape": "tables", "chars": 6000, "chunk_chars": 24},
                {"tool_calls": [["read", {"path": "{cwd}/README.md"}]]} ]}

Step keys: text | shape+chars (generated by mock/shapes.py), tool_calls (list of [name, arguments]; `{cwd}` expands to the project directory), chunk_chars,
event_delay_ms, delay_ms, usage_prompt, arg_chunk_chars (characters per streamed piece of a tool call's arguments; default two halves). Unknown keys are an error.
"""
import json

from . import server, shapes

STEP_KEYS = {"text", "shape", "chars", "tool_calls", "chunk_chars", "event_delay_ms", "delay_ms", "usage_prompt", "arg_chunk_chars"}


class TranscriptError(ValueError):
    pass


def expand_cwd(value, cwd):
    """`{cwd}` replaced inside every string of a decoded value: a directory holding a quote or a backslash cannot break the JSON, and each string is replaced as text."""
    if isinstance(value, str):
        return value.replace("{cwd}", cwd)
    if isinstance(value, list):
        return [expand_cwd(v, cwd) for v in value]
    if isinstance(value, dict):
        return {k: expand_cwd(v, cwd) for k, v in value.items()}
    return value


def step_from(spec, cwd=""):
    unknown = set(spec) - STEP_KEYS
    if unknown:
        raise TranscriptError(f"unknown step key(s): {', '.join(sorted(unknown))}")
    text = spec.get("text")
    if "shape" in spec:
        if spec["shape"] not in shapes.SHAPES:
            raise TranscriptError(f"unknown shape {spec['shape']!r}; use one of {', '.join(shapes.SHAPES)}")
        if text is not None or "chars" not in spec:
            raise TranscriptError("a shape step has `chars` and no `text`")
        text = shapes.body(spec["shape"], int(spec["chars"]))
    calls = [(name, expand_cwd(args, cwd)) for name, args in spec.get("tool_calls", [])]
    if text is None and not calls:
        raise TranscriptError("a step needs text, a shape or tool_calls")
    return server.Step(text=text, tool_calls=calls, usage_prompt=spec.get("usage_prompt"), delay_ms=spec.get("delay_ms", 0), event_delay_ms=spec.get("event_delay_ms", 0),
                       chunk_chars=spec.get("chunk_chars", 0), arg_chunk_chars=spec.get("arg_chunk_chars", 0))


class Transcript:
    def __init__(self, data, cwd=""):
        if isinstance(data, str):
            with open(data) as f:
                data = json.load(f)
        if set(data) - {"name", "steps"} or not data.get("steps"):
            raise TranscriptError("a transcript has `name` and a non-empty `steps` list")
        self.name = data.get("name", "")
        self.steps = [step_from(s, cwd) for s in data["steps"]]

    def policy(self):
        """Stateless: request i gets step i, the last step repeats, so a retried or replayed request sequence gets the same replies."""
        steps = self.steps

        def policy(request):
            return steps[min(request.index, len(steps) - 1)]

        return policy
